# Install, start, stop, and roll back the samantha-local user supervisor.
# Linux only. No sudo. No system unit. Does not edit /etc/wsl.conf.
# --prefix writes a throwaway layout and does not talk to systemd.

set -euo pipefail
export LC_ALL=C

ROOT=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
src_script=$ROOT/supervise.sh
src_unit=$ROOT/samantha-local.service
src_env=$ROOT/samantha-local.env.example

cmd=
prefix_arg=
dry_run=0
prefix=
prefix_is_home=0
dest_bin=
dest_unit=
dest_bak=
dest_drop_dir=
dest_drop=
dest_env=

die() {
  local code=$1
  shift
  printf 'samantha-linux: %s\n' "$*" >&2
  exit "$code"
}

usage() {
  cat <<'EOF'
usage: install.sh [install|enable|start|stop|logs|status|rollback] [--prefix DIR] [--dry-run]

  install    copy the user unit, the supervisor, and the example env file
  enable     systemctl --user enable (boot autostart when the user session starts)
  start      systemctl --user start, or the foreground restart loop
  stop       systemctl --user stop, or signal the restart loop
  logs       journalctl --user -u samantha-local.service
  status     systemctl --user status, or the restart-loop pid
  rollback   disable the unit, restore a backed-up unit, remove this install
  --prefix   write under DIR and do not call systemctl
  --dry-run  print the install or rollback plan and write nothing
EOF
}

systemd_user_ready() {
  command -v systemctl >/dev/null 2>&1 || return 1
  [[ -d /run/systemd/system ]] || return 1
  systemctl --user show-environment >/dev/null 2>&1
}

using_systemd() {
  ((prefix_is_home == 1)) || return 1
  systemd_user_ready
}

write_text() {
  local dest=$1 mode=$2 tmp
  tmp=$(mktemp)
  cat >"$tmp"
  if [[ -f "$dest" ]] && cmp -s "$tmp" "$dest"; then
    rm -f -- "$tmp"
    printf 'unchanged %s\n' "$dest"
    return 0
  fi
  if ((dry_run == 1)); then
    rm -f -- "$tmp"
    printf 'dry-run: would install %s\n' "$dest"
    return 0
  fi
  mkdir -p -- "$(dirname -- "$dest")"
  cp -- "$tmp" "$dest"
  chmod "$mode" "$dest"
  rm -f -- "$tmp"
  printf 'installed %s\n' "$dest"
}

copy_file() {
  local src=$1 dest=$2 mode=$3
  write_text "$dest" "$mode" <"$src"
}

backup_unit() {
  if [[ ! -f "$dest_unit" ]] || cmp -s "$src_unit" "$dest_unit"; then
    return 0
  fi
  if [[ -f "$dest_bak" ]]; then
    printf 'keeping %s\n' "$dest_bak"
    return 0
  fi
  if ((dry_run == 1)); then
    printf 'dry-run: would back up %s\n' "$dest_unit"
    return 0
  fi
  cp -- "$dest_unit" "$dest_bak"
  chmod 644 "$dest_bak"
  printf 'backed up %s\n' "$dest_bak"
}

install_env() {
  if [[ -f "$dest_env" ]]; then
    printf 'unchanged %s\n' "$dest_env"
    return 0
  fi
  if ((dry_run == 1)); then
    printf 'dry-run: would install %s\n' "$dest_env"
    printf 'edit the env file before enable\n'
    return 0
  fi
  local old_umask
  old_umask=$(umask)
  mkdir -p -- "$(dirname -- "$dest_env")"
  umask 077
  cp -- "$src_env" "$dest_env"
  chmod 600 "$dest_env"
  umask "$old_umask"
  printf 'installed %s\n' "$dest_env"
  printf 'edit %s before enable\n' "$dest_env"
}

dropin_text() {
  local bin_path=$1 ui_path=$2 work_path=$3
  printf '%s\n' '# Generated by deploy/linux/install.sh. Re-run install after editing the env file.'
  printf '%s\n' '[Service]'
  if [[ -n "$bin_path" && -e "$bin_path" ]]; then
    printf 'ReadOnlyPaths=%s\n' "$bin_path"
  fi
  if [[ -n "$ui_path" && -d "$ui_path" ]]; then
    printf 'ReadOnlyPaths=%s\n' "$ui_path"
  fi
  if [[ -n "$work_path" && -d "$work_path" ]]; then
    printf 'ReadWritePaths=%s\n' "$work_path"
  fi
}

read_paths() {
  local line
  bin_path=
  ui_path=
  work_path=
  [[ -f "$dest_env" ]] || return 0
  while IFS= read -r line; do
    case "$line" in
      bind=*) ;;
      bin=*) bin_path=${line#bin=} ;;
      ui=*) ui_path=${line#ui=} ;;
      workdir=*) work_path=${line#workdir=} ;;
      '') ;;
      *) die 2 "unexpected path line from supervise.sh" ;;
    esac
  done < <("$src_script" --paths --env "$dest_env")
}

install_dropin() {
  local bin_path='' ui_path='' work_path=''
  if [[ ! -f "$dest_env" ]]; then
    if ((dry_run == 1)); then
      printf 'dry-run: would install %s\n' "$dest_drop"
    fi
    return 0
  fi
  read_paths
  dropin_text "$bin_path" "$ui_path" "$work_path" | write_text "$dest_drop" 644
}

reload_user() {
  if ! using_systemd; then
    return 0
  fi
  if ((dry_run == 1)); then
    printf 'dry-run: would systemctl --user daemon-reload\n'
    return 0
  fi
  systemctl --user daemon-reload
}

cmd_install() {
  backup_unit
  copy_file "$src_script" "$dest_bin" 755
  copy_file "$src_unit" "$dest_unit" 644
  install_env
  install_dropin
  reload_user
  if ((dry_run == 1)); then
    printf 'GALION_LINUX_SUPERVISE=dry-run\n'
  else
    printf 'GALION_LINUX_SUPERVISE=installed\n'
  fi
}

no_systemd_hint() {
  printf 'systemd user session is unavailable.\n' >&2
  printf 'Boot autostart needs that session. On WSL, set systemd=true under [boot] in /etc/wsl.conf, then start the distro again.\n' >&2
  printf 'This installer does not edit that file.\n' >&2
  printf 'Until then, run: %s\n' "$dest_bin" >&2
}

cmd_enable() {
  if ((prefix_is_home != 1)); then
    die 2 "enable talks to the user systemd session and refuses --prefix"
  fi
  if ! systemd_user_ready; then
    no_systemd_hint
    exit 2
  fi
  if [[ ! -f "$dest_unit" || ! -x "$dest_bin" ]]; then
    die 2 "run install before enable"
  fi
  if ((dry_run == 1)); then
    "$dest_bin" --check --env "$dest_env"
    printf 'dry-run: would systemctl --user enable samantha-local.service\n'
    return 0
  fi
  "$dest_bin" --check --env "$dest_env"
  systemctl --user daemon-reload
  systemctl --user enable samantha-local.service
  printf 'enabled samantha-local.service\n'
  printf 'The unit starts with the next user session. For a boot start, the session has to come up too: loginctl enable-linger "%s"\n' "$(id -un)"
  printf 'This installer does not run loginctl and does not edit /etc/wsl.conf.\n'
}

cmd_start() {
  if ((prefix_is_home != 1)); then
    die 2 "start refuses --prefix"
  fi
  if systemd_user_ready; then
    if ((dry_run == 1)); then
      printf 'dry-run: would systemctl --user start samantha-local.service\n'
      return 0
    fi
    systemctl --user start samantha-local.service
    printf 'started samantha-local.service\n'
    return 0
  fi
  if [[ ! -x "$dest_bin" ]]; then
    die 2 "run install before start"
  fi
  if ((dry_run == 1)); then
    printf 'dry-run: would run %s\n' "$dest_bin"
    return 0
  fi
  printf 'systemd user session is unavailable. Starting the restart loop in the foreground.\n' >&2
  exec "$dest_bin"
}

cmd_stop() {
  local tool=$src_script
  if ((prefix_is_home == 1)) && systemd_user_ready; then
    if ((dry_run == 1)); then
      printf 'dry-run: would systemctl --user stop samantha-local.service\n'
      return 0
    fi
    systemctl --user stop samantha-local.service
    printf 'stopped samantha-local.service\n'
    return 0
  fi
  if [[ -x "$dest_bin" ]]; then
    tool=$dest_bin
  fi
  if ((dry_run == 1)); then
    printf 'dry-run: would stop the restart loop\n'
    return 0
  fi
  "$tool" --stop
}

cmd_logs() {
  if ((prefix_is_home == 1)) && systemd_user_ready; then
    if ((dry_run == 1)); then
      printf 'dry-run: would journalctl --user -u samantha-local.service -n 200 --no-pager\n'
      return 0
    fi
    exec journalctl --user -u samantha-local.service -n 200 --no-pager
  fi
  printf 'The restart loop writes to the terminal that started it.\n'
  printf 'With a user session: journalctl --user -u samantha-local.service -f\n'
}

cmd_status() {
  local tool=$src_script
  if ((prefix_is_home == 1)) && systemd_user_ready; then
    systemctl --user status samantha-local.service --no-pager
    return 0
  fi
  if [[ -x "$dest_bin" ]]; then
    tool=$dest_bin
  fi
  "$tool" --status
}

remove_dropin() {
  case "$dest_drop_dir" in
    "$prefix"/.config/systemd/user/samantha-local.service.d) ;;
    *) die 2 "refusing to remove ${dest_drop_dir}" ;;
  esac
  if [[ ! -d "$dest_drop_dir" ]]; then
    return 0
  fi
  if ((dry_run == 1)); then
    printf 'dry-run: would remove %s\n' "$dest_drop_dir"
    return 0
  fi
  rm -rf -- "$dest_drop_dir"
  printf 'removed %s\n' "$dest_drop_dir"
}

cmd_rollback() {
  if ((prefix_is_home == 1)) && systemd_user_ready; then
    if ((dry_run == 1)); then
      printf 'dry-run: would systemctl --user disable --now samantha-local.service\n'
    else
      systemctl --user disable --now samantha-local.service || true
    fi
  elif ((dry_run == 0)); then
    if [[ -x "$dest_bin" ]]; then
      "$dest_bin" --stop || true
    else
      "$src_script" --stop || true
    fi
  fi
  if [[ -f "$dest_bak" ]]; then
    if ((dry_run == 1)); then
      printf 'dry-run: would restore %s\n' "$dest_unit"
    else
      mv -- "$dest_bak" "$dest_unit"
      chmod 644 "$dest_unit"
      printf 'restored %s\n' "$dest_unit"
    fi
  elif [[ -f "$dest_unit" ]]; then
    if ((dry_run == 1)); then
      printf 'dry-run: would remove %s\n' "$dest_unit"
    else
      rm -f -- "$dest_unit"
      printf 'removed %s\n' "$dest_unit"
    fi
  fi
  remove_dropin
  if [[ -f "$dest_bin" ]]; then
    if ((dry_run == 1)); then
      printf 'dry-run: would remove %s\n' "$dest_bin"
    else
      rm -f -- "$dest_bin"
      printf 'removed %s\n' "$dest_bin"
    fi
  fi
  if [[ -f "$dest_env" ]]; then
    printf 'kept %s\n' "$dest_env"
  fi
  reload_user
  printf 'GALION_LINUX_SUPERVISE=rolled-back\n'
}

resolve_prefix() {
  if [[ -z "$prefix_arg" ]]; then
    [[ -n "${HOME:-}" ]] || die 2 "HOME is unset. Pass --prefix."
    prefix=$HOME
    prefix_is_home=1
  else
    prefix=$prefix_arg
    if [[ "$prefix" != /* ]]; then
      prefix=$PWD/$prefix
    fi
    if [[ -d "$prefix" ]]; then
      prefix=$(CDPATH='' cd -- "$prefix" && pwd)
    fi
    prefix=${prefix%/}
    if [[ "$prefix" == "$HOME" ]]; then
      prefix_is_home=1
    fi
  fi
  [[ -n "$prefix" && "$prefix" != "/" ]] || die 2 "refusing prefix"
  case "$prefix" in
    *[[:space:]]* | *'*'* | *'?'* | *'['*) die 2 "prefix has unsafe characters" ;;
  esac
  if ((prefix_is_home == 1)) && [[ "$(id -u)" -eq 0 ]]; then
    die 2 "refusing root's home. Pass --prefix for a throwaway directory."
  fi
  dest_bin=$prefix/.local/bin/samantha-local-supervise
  dest_unit=$prefix/.config/systemd/user/samantha-local.service
  dest_bak=$prefix/.config/systemd/user/samantha-local.service.bak
  dest_drop_dir=$prefix/.config/systemd/user/samantha-local.service.d
  dest_drop=$dest_drop_dir/paths.conf
  dest_env=$prefix/.config/galion/samantha-local.env
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    install | enable | start | stop | logs | status | rollback)
      [[ -z "$cmd" ]] || die 2 "two commands"
      cmd=$1
      shift
      ;;
    --prefix)
      [[ $# -ge 2 ]] || die 2 "--prefix needs a directory"
      prefix_arg=$2
      shift 2
      ;;
    --dry-run)
      dry_run=1
      shift
      ;;
    -h | --help)
      usage
      exit 0
      ;;
    *) die 2 "unknown argument ${1}" ;;
  esac
done

cmd=${cmd:-install}
resolve_prefix

case "$cmd" in
  install) cmd_install ;;
  enable) cmd_enable ;;
  start) cmd_start ;;
  stop) cmd_stop ;;
  logs) cmd_logs ;;
  status) cmd_status ;;
  rollback) cmd_rollback ;;
  *) die 2 "unknown command ${cmd}" ;;
esac
